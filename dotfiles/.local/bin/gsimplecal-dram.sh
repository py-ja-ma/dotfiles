#!/usr/bin/env bash
# usage: gsimplecal-dram.sh
#
# Launches gsimplecal themed to the current dram theme (the bar's date click).
# gsimplecal has no stylesheet option, so this points XDG_CONFIG_HOME at a
# private directory under $XDG_RUNTIME_DIR, rebuilt on every click, whose
# gtk-3.0/gtk.css imports ~/.config/themes/current/waybar.css (the palette) and
# ~/.config/gsimplecal/gtk.css (the rules); settings.ini and gsimplecal/config
# are links to the real ones. Nothing else sees it.
#
#   -h, --help    this text
#
# exit: 0 ok · 1 launch failed · 2 bad usage
# see: dotfiles/.config/gsimplecal/README.md

case "${1:-}" in
  "") ;;
  -h | --help)
    sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  *)
    sed -n '2s/^# \{0,1\}//p' "$0" >&2
    exit 2
    ;;
esac

# gsimplecal (2.5.x) has no stylesheet option: its config parser knows 19 keys
# and none of them is CSS, so the old `maincss_file` line was silently ignored
# and the popup came up on bare Adwaita — Noto Sans, a filled pill on today, a
# 2 px frame. It also installs no GtkCssProvider of its own, which means the
# GTK3 user stylesheet ($XDG_CONFIG_HOME/gtk-3.0/gtk.css, priority 800, above
# the theme's 200 and the application's 600) is the one lever left: point
# XDG_CONFIG_HOME at a private directory for this process only. Nothing else
# sees it.
#
# The private config home lives under $XDG_RUNTIME_DIR (tmpfs, per login) and
# is rebuilt on every click — cheap, and it is how the popup follows SUPER+T:
#  gtk-3.0/gtk.css      @imports ~/.config/themes/current/waybar.css (palette)
#                       and then ~/.config/gsimplecal/gtk.css (the rules)
#  gtk-3.0/settings.ini a link to the real one (theme name, font, prefer-dark)
#  gsimplecal/config    a link to the real one (gsimplecal reads it from
#                       $XDG_CONFIG_HOME too, so it must be there)
# The window keeps its app_id "gsimplecal" (GTK uses the program name), so the
# place-gsimplecal rule in hyprland.lua still floats, places and rounds it.

set -euo pipefail

CFG="$HOME/.config"
PAL="$CFG/themes/current/waybar.css"
CSS="$CFG/gsimplecal/gtk.css"
RT="${XDG_RUNTIME_DIR:-/tmp/gsimplecal-dram-$(id -u)}/gsimplecal-dram"
mkdir -p "$RT/gtk-3.0" "$RT/gsimplecal"
# fontconfig reads $XDG_CONFIG_HOME/fontconfig too; without this link the Nix
# font dirs (10-hm-fonts.conf) vanish and every glyph falls back to Noto Sans.
[ -d "$CFG/fontconfig" ] && ln -sfn "$CFG/fontconfig" "$RT/fontconfig"

# the user stylesheet: palette first (defines @base @text @subtext @accent …),
# rules second. Absolute paths — a relative @import would resolve against $RT.
{
  echo '/* GENERATED by gsimplecal-dram.sh on every launch — edit gsimplecal/gtk.css instead */'
  [ -r "$PAL" ] && printf '@import url("%s");\n' "$PAL"
  [ -r "$CSS" ] && printf '@import url("%s");\n' "$CSS"
} >"$RT/gtk-3.0/gtk.css"

# keep theme name / font / prefer-dark by borrowing the real gtk-3.0 settings.ini
if [ -e "$CFG/gtk-3.0/settings.ini" ]; then
  ln -sfn "$CFG/gtk-3.0/settings.ini" "$RT/gtk-3.0/settings.ini"
else
  rm -f "$RT/gtk-3.0/settings.ini"
fi
# gsimplecal's own config must be reachable through the redirected home
ln -sfn "$CFG/gsimplecal/config" "$RT/gsimplecal/config"

exec env XDG_CONFIG_HOME="$RT" gsimplecal "$@"

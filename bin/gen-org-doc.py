#!/usr/bin/env python3
"""usage: gen-org-doc.py [--check]

Writes the generated parts of the organization's pages, from the files that hold the
facts. The chart in README.md and docs/README.md (the lines between the
`<!-- chart -->` and `<!-- /chart -->` markers) comes from the chart rows of
docs/map.tsv. decisions/README.md, the index of the decision records, comes from the
title and status line of each decisions/NNNN-*.md and from the sections of
decisions/log.md: the open and held decisions, and the decisions of each division.
Deterministic: running it twice produces no diff. Needs only python3; runs on the Mac.
bin/check.sh §23 runs it with --check.

A record's head is `# NNNN: <decision>`, then one line:
`[<Directorate> › <Division>](<page>) · <status> <YYYY-MM-DD>[ · <relation>]...`.
A log section is `### D<n>`, the decision, then a status line that starts with
Decided, Open since, Held since or Superseded by, then ` · <Directorate › Division>`.

  --check       write nothing; exit 1 (with a diff) when a page is stale
  -h, --help    this text

exit: 0 ok · 1 --check found a difference, or a record or log section is malformed · 2 bad usage
see: docs/map.tsv, decisions/log.md, docs/records/README.md
"""
import difflib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = os.path.join(ROOT, "docs", "map.tsv")
DECISIONS = os.path.join(ROOT, "decisions")
LOG = os.path.join(DECISIONS, "log.md")
INDEX = os.path.join(DECISIONS, "README.md")
CHART_PAGES = [os.path.join(ROOT, "README.md"), os.path.join(ROOT, "docs", "README.md")]
BEGIN = "<!-- chart: generated by bin/gen-org-doc.py from docs/map.tsv; edit the map, not this table -->"
END = "<!-- /chart -->"
SEP = " › "
STATUS_WORDS = ("Decided", "Open since", "Held since", "Superseded by", "Withdrawn")


class Malformed(Exception):
    pass


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def chart():
    """[(node, title, page)] in the map's order; node is 'dir' or 'dir/div'."""
    out = []
    for line in read(MAP).split("\n"):
        if line.startswith("="):
            cols = line[1:].split("\t")
            if len(cols) != 3:
                raise Malformed("docs/map.tsv: bad chart row: %s" % line)
            out.append(tuple(cols))
    return out


def titles(nodes):
    """'Directorate › Division' (and 'Directorate') -> node."""
    by_node = {n: t for n, t, _ in nodes}
    out = {}
    for n, t, _ in nodes:
        if "/" in n:
            out[by_node[n.split("/")[0]] + SEP + t] = n
        else:
            out[t] = n
    return out


def rel(from_dir, path):
    return os.path.relpath(os.path.join(ROOT, path), os.path.join(ROOT, from_dir)).replace(os.sep, "/")


# --------------------------------------------------------------------------- the chart
def chart_table(nodes, page_dir):
    rows = ["| Directorate | Divisions |", "|---|---|"]
    tops = [(n, t, p) for n, t, p in nodes if "/" not in n]
    for n, t, p in tops:
        divs = [(dn, dt, dp) for dn, dt, dp in nodes if dn.startswith(n + "/")]
        cells = " · ".join("[%s](%s)" % (dt, rel(page_dir, dp)) for _, dt, dp in divs)
        rows.append("| [%s](%s) | %s |" % (t, rel(page_dir, p), cells))
    return "\n".join(rows)


def with_chart(path, nodes):
    text = read(path)
    if BEGIN not in text or END not in text:
        raise Malformed("%s has no chart markers (%s … %s)" % (os.path.relpath(path, ROOT), BEGIN, END))
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    page_dir = os.path.dirname(os.path.relpath(path, ROOT))
    return head + BEGIN + "\n" + chart_table(nodes, page_dir) + "\n" + END + tail


# --------------------------------------------------------------------------- the records
HEAD = re.compile(r"^# (\d{4}): (.+)$")
OWNER = re.compile(r"^\[([^\]]+)\]\(([^)]+)\)((?: · [^·]+)+)$")
STATUS = re.compile(r"^(proposed|accepted|superseded by \d{4}|withdrawn) (\d{4}-\d{2}-\d{2})$")


def records(known):
    out = []
    for name in sorted(os.listdir(DECISIONS)):
        if not re.match(r"^\d{4}-.+\.md$", name):
            continue
        lines = [l.rstrip() for l in read(os.path.join(DECISIONS, name)).split("\n")]
        m = HEAD.match(lines[0]) if lines else None
        if not m or m.group(1) != name[:4]:
            raise Malformed("decisions/%s: line 1 is not '# %s: <decision>'" % (name, name[:4]))
        body = [l for l in lines[1:] if l.strip()]
        o = OWNER.match(body[0]) if body else None
        if not o:
            raise Malformed("decisions/%s: the line under the title is not "
                            "'[<Directorate> › <Division>](<page>) · <status> <date>'" % name)
        owner = o.group(1)
        if owner not in known:
            raise Malformed("decisions/%s: owner %r is not a directorate or division of docs/map.tsv" % (name, owner))
        parts = [p.strip() for p in o.group(3).split(" · ") if p.strip()]
        s = STATUS.match(parts[0])
        if not s:
            raise Malformed("decisions/%s: status %r is not proposed, accepted, superseded by NNNN or "
                            "withdrawn, then a date" % (name, parts[0]))
        out.append({"no": name[:4], "file": name, "title": m.group(2), "owner": owner,
                    "status": parts[0], "relations": parts[1:]})
    return out


# --------------------------------------------------------------------------- the log
def log_sections(known):
    text = read(LOG)
    out, cur = [], None
    for line in text.split("\n"):
        m = re.match(r"^### D(\d+)\s*$", line)
        if m:
            cur = {"n": int(m.group(1)), "paras": [[]]}
            out.append(cur)
            continue
        if line.startswith("#"):
            cur = None
            continue
        if cur is None:
            continue
        if line.strip():
            cur["paras"][-1].append(line.strip())
        elif cur["paras"][-1]:
            cur["paras"].append([])
    entries = []
    for i, s in enumerate(out):
        paras = [p for p in s["paras"] if p]
        if s["n"] != i + 1:
            raise Malformed("decisions/log.md: D%d follows D%d (the log runs D1, D2, … without gaps)"
                            % (s["n"], out[i - 1]["n"] if i else 0))
        if len(paras) < 2:
            raise Malformed("decisions/log.md: D%d needs the decision and a status line" % s["n"])
        status = " ".join(paras[-1])
        if not status.startswith(STATUS_WORDS):
            raise Malformed("decisions/log.md: D%d: the last paragraph starts with none of %s"
                            % (s["n"], ", ".join(STATUS_WORDS)))
        segs = [x.strip() for x in status.split(" · ")]
        if len(segs) < 2 or segs[1] not in known:
            raise Malformed("decisions/log.md: D%d: %r is not a directorate or division of docs/map.tsv"
                            % (s["n"], segs[1] if len(segs) > 1 else ""))
        date = re.search(r"\d{4}-\d{2}-\d{2}", segs[0])
        word = next(w for w in STATUS_WORDS if segs[0].startswith(w))
        # the summary moves from log.md to README.md: a link to a section of the log keeps working
        summary = paras[0][0].replace("](#", "](log.md#")
        entries.append({"n": s["n"], "summary": summary, "status": word,
                        "since": date.group(0) if date else "", "owner": segs[1]})
    return entries


def index_page(nodes, recs, entries):
    o = []
    o.append("<!-- GENERATED by bin/gen-org-doc.py from the records in decisions/ and decisions/log.md; "
             "edit those, not this page (bin/check.sh §23 fails when it is stale). -->")
    o.append("# Decisions")
    o.append("")
    o.append("[Office of Records](../docs/records/README.md) › Decisions")
    o.append("")
    o.append("Why the repo is the way it is, kept in two forms.")
    o.append("A decision record explains one larger choice: its context, the alternatives, "
             "the consequences, and the check that fails when it stops holding.")
    o.append("The [decision log](log.md) holds every numbered decision, one or two sentences "
             "each, with its status and the record or code that carries it.")
    o.append("A number of either kind is never reused, and a superseded decision stays, "
             "linked to its successor.")
    o.append("")
    o.append("## Records")
    o.append("")
    o.append("| No. | Decision | Status | Owner |")
    o.append("|---|---|---|---|")
    for r in recs:
        status = r["status"] + "".join(" · " + x for x in r["relations"])
        o.append("| [%s](%s) | %s | %s | %s |" % (r["no"], r["file"], r["title"], status, r["owner"]))
    o.append("")
    for word, head, lead in (
            ("Open since", "Open decisions", "Decisions that wait on me, oldest first."),
            ("Held since", "Held decisions", "Decided, and waiting on a named condition before anything is built.")):
        rows = [e for e in entries if e["status"] == word]
        if not rows:
            continue
        o.append("## %s" % head)
        o.append("")
        o.append(lead)
        o.append("")
        o.append("| Decision | Since | Owner |")
        o.append("|---|---|---|")
        for e in sorted(rows, key=lambda e: (e["since"], e["n"])):
            o.append("| [D%d](log.md#d%d): %s | %s | %s |" % (e["n"], e["n"], e["summary"], e["since"], e["owner"]))
        o.append("")
    o.append("## By division")
    o.append("")
    o.append("| Owner | Records | Decisions |")
    o.append("|---|---|---|")
    by_node = {n: t for n, t, _ in nodes}
    for n, t, _ in nodes:
        name = t if "/" not in n else by_node[n.split("/")[0]] + SEP + t
        rs = [r for r in recs if r["owner"] == name]
        es = [e for e in entries if e["owner"] == name]
        if not rs and not es:
            continue
        o.append("| %s | %s | %s |" % (
            name,
            ", ".join("[%s](%s)" % (r["no"], r["file"]) for r in rs) or "none",
            ", ".join("[D%d](log.md#d%d)" % (e["n"], e["n"]) for e in es) or "none"))
    o.append("")
    return "\n".join(o)


# --------------------------------------------------------------------------- main
def main(argv):
    check = False
    for a in argv:
        if a in ("-h", "--help"):
            print(__doc__.strip("\n"))
            return 0
        if a == "--check":
            check = True
        else:
            print("gen-org-doc.py: unknown argument: %s" % a, file=sys.stderr)
            print(__doc__.split("\n", 1)[0], file=sys.stderr)
            return 2
    try:
        nodes = chart()
        known = titles(nodes)
        pages = {p: with_chart(p, nodes) for p in CHART_PAGES}
        pages[INDEX] = index_page(nodes, records(known), log_sections(known))
    except (Malformed, OSError) as e:
        print("gen-org-doc.py: %s" % e, file=sys.stderr)
        return 1
    stale = 0
    for path, new in pages.items():
        old = read(path) if os.path.exists(path) else ""
        if old == new:
            continue
        name = os.path.relpath(path, ROOT)
        if check:
            stale += 1
            diff = difflib.unified_diff(old.split("\n"), new.split("\n"), name, name + " (generated)", lineterm="", n=1)
            print("\n".join(list(diff)[:40]))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            print("wrote %s" % name)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
